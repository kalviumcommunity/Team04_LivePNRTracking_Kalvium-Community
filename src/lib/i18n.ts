export function getSavedLanguage(): LanguageCode {
  if (typeof window === "undefined") return "en";
  const saved = localStorage.getItem("app_language");
  const valid = SUPPORTED_LANGUAGES.some((l) => l.code === saved);
  if (valid && saved) {
    return saved as LanguageCode;
  }
  return "en";
}

export function setSavedLanguage(code: LanguageCode) {
  if (typeof window === "undefined") return;
  localStorage.setItem("app_language", code);
  window.dispatchEvent(new CustomEvent("languageChange", { detail: code }));
}

export function t(key: string, lang?: LanguageCode): string {
  const currentLang = lang || getSavedLanguage();
  const langDict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return langDict[key] || TRANSLATIONS.en[key] || key;
}

export function useTranslation() {
  const [lang, setLang] = useState<LanguageCode>(() => getSavedLanguage());

  useEffect(() => {
    const handleLangChange = (e: CustomEvent<LanguageCode>) => {
      setLang(e.detail);
    };
    window.addEventListener("languageChange", handleLangChange as EventListener);
    return () => {
      window.removeEventListener("languageChange", handleLangChange as EventListener);
    };
  }, []);

  const translate = (key: string) => t(key, lang);

  return { lang, t: translate };
}
